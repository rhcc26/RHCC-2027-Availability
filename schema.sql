create extension if not exists pgcrypto;
create table if not exists public.profiles (
 id uuid primary key references auth.users(id) on delete cascade,
 email text not null,
 display_name text not null default '',
 role text not null default 'player' check(role in ('admin','captain','player')),
 approved boolean not null default false,
 created_at timestamptz not null default now()
);
create table if not exists public.fixtures (
 id bigint generated by default as identity primary key,
 match_date date not null,
 opponent text not null,
 match_type text not null check(match_type in ('League','Cup')),
 venue text not null check(venue in ('Home','Away','TBC')),
 notes text not null default ''
);
create table if not exists public.availability (
 fixture_id bigint not null references public.fixtures(id) on delete cascade,
 player_id uuid not null references public.profiles(id) on delete cascade,
 status text not null check(status in ('Available','Unavailable','Not Sure')),
 updated_at timestamptz not null default now(),
 primary key(fixture_id,player_id)
);
create or replace function public.current_role() returns text language sql stable security definer set search_path = '' as $$ select role from public.profiles where id = (select auth.uid()) and approved = true $$;
create or replace function public.is_admin() returns boolean language sql stable security definer set search_path = '' as $$ select coalesce(public.current_role() = 'admin',false) $$;
create or replace function public.is_approved() returns boolean language sql stable security definer set search_path = '' as $$ select exists(select 1 from public.profiles where id=(select auth.uid()) and approved=true) $$;
create or replace function public.create_profile() returns trigger language plpgsql security definer set search_path = '' as $$ begin insert into public.profiles(id,email,display_name) values(new.id,coalesce(new.email,''),coalesce(new.raw_user_meta_data->>'display_name',split_part(coalesce(new.email,''),'@',1))) on conflict(id) do nothing; return new; end $$;
drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created after insert on auth.users for each row execute function public.create_profile();
insert into public.profiles(id,email,display_name) select id,coalesce(email,''),coalesce(raw_user_meta_data->>'display_name',split_part(coalesce(email,''),'@',1)) from auth.users on conflict(id) do nothing;
alter table public.profiles enable row level security;
alter table public.fixtures enable row level security;
alter table public.availability enable row level security;
create policy "profiles read" on public.profiles for select to authenticated using (id=(select auth.uid()) or public.is_admin() or public.current_role()='captain');
create policy "admin update profiles" on public.profiles for update to authenticated using(public.is_admin()) with check(public.is_admin());
create policy "admin insert profiles" on public.profiles for insert to authenticated with check(public.is_admin());
create policy "admin delete profiles" on public.profiles for delete to authenticated using(public.is_admin() and id<>(select auth.uid()));
create policy "fixtures read" on public.fixtures for select to authenticated using(public.is_approved());
create policy "fixtures insert" on public.fixtures for insert to authenticated with check(public.is_admin());
create policy "fixtures update" on public.fixtures for update to authenticated using(public.is_admin()) with check(public.is_admin());
create policy "fixtures delete" on public.fixtures for delete to authenticated using(public.is_admin());
create policy "availability read" on public.availability for select to authenticated using(public.is_approved() and (player_id=(select auth.uid()) or public.current_role() in ('admin','captain')));
create policy "availability insert own" on public.availability for insert to authenticated with check(public.is_approved() and player_id=(select auth.uid()));
create policy "availability update own" on public.availability for update to authenticated using(public.is_approved() and player_id=(select auth.uid())) with check(public.is_approved() and player_id=(select auth.uid()));
create policy "availability delete own" on public.availability for delete to authenticated using(public.is_approved() and player_id=(select auth.uid()));
